test_that("boxplots compare one mean per column with mappings matched by name", {
  spe <- result_spe()
  spe$custom_score <- c(-5, 2, 0, 8, 3, 4)
  spe$zero <- rep(0, 6)
  columns <- c("custom_score", "quantiseq_B", "zero", "quantiseq_A")
  groups <- c(quantiseq_A = "Cells", zero = "Score", quantiseq_B = "Cells", custom_score = "Score")
  sources <- c(zero = "B", quantiseq_A = "B", custom_score = "A", quantiseq_B = "A")
  p <- plot_boxplot(spe, columns, groups, sources, title = "Comparison",
    xlab = "Feature", ylab = "Mean abundance", colors = c(B = "red", A = "blue"))
  expect_equal(p$data$mean, unname(colMeans(as.matrix(colData(spe)[, columns]))))
  expect_identical(p$data$column, columns)
  expect_identical(as.character(p$data$group), c("Score", "Cells", "Score", "Cells"))
  expect_identical(as.character(p$data$source), c("A", "A", "B", "B"))
  expect_identical(levels(p$data$group), c("Score", "Cells"))
  expect_identical(p$labels$y, "Mean abundance")
  expect_renderable(p)
  built <- ggplot2::ggplot_build(p)
  expect_equal(sort(built$data[[2]]$y), sort(p$data$mean))
  expect_equal(nrow(built$data[[1]]), 2)
  # Quartiles must summarize column means, not the individual spot values.
  expect_equal(built$data[[1]]$middle, c(1, .5))
  expect_equal(built$data[[1]]$lower, c(.5, .5))
  expect_equal(built$data[[1]]$upper, c(1.5, .5))
})

test_that("boxplot means use the same complete spots and retain constant zeros", {
  spe <- result_spe()
  spe$a <- c(NA, 2, Inf, 4, 8, 6)
  spe$b <- c(1, 0, 2, 0, 0, 0)
  groups <- c(a = "Cells", b = "Cells")
  sources <- c(a = "A", b = "B")
  expect_warning(p <- plot_boxplot(spe, c("a", "b"), groups, sources), "2 spots")
  expect_equal(p$data$mean, c(5, 0))
  expect_renderable(p)
  spe$a <- rep(NA_real_, 6)
  expect_error(suppressWarnings(plot_boxplot(spe, c("a", "b"), groups, sources)), "complete spot")
})

test_that("boxplots reject invalid selections and ambiguous mappings", {
  spe <- result_spe()
  columns <- c("quantiseq_A", "quantiseq_B")
  groups <- setNames(c("Cells", "Cells"), columns)
  sources <- setNames(c("A", "B"), columns)
  expect_error(plot_boxplot(spe, c("missing", columns), groups, sources), "do not exist")
  expect_error(plot_boxplot(spe, c("sample_id", columns), groups, sources), "numeric")
  expect_error(plot_boxplot(spe, rep(columns[1], 2), groups, sources), "distinct")
  expect_error(plot_boxplot(spe, columns, unname(groups), sources), "named")
  expect_error(plot_boxplot(spe, columns, groups, sources[1]), "covering")
  expect_error(plot_boxplot(spe, columns, groups, groups), "group/source pair")
  expect_error(plot_boxplot(spe, columns, groups, sources, colors = c(A = "red")), "covering")
})
